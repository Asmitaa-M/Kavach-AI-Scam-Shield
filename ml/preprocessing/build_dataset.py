def fill(t):
    b = bank()
    return (t.replace("{a}", amt()).replace("{b}", b).replace("{b2}", b.split()[0].lower())
             .replace("{n}", num4()).replace("{nm}", name()))

rows = []
for lang, ts in SCAM.items():
    for t in ts:
        for _ in range(14):
            rows.append({"text": fill(t), "label": 1, "lang": lang, "source": "synthetic"})
for lang, ts in LEGIT.items():
    for t in ts:
        for _ in range(14):
            rows.append({"text": fill(t), "label": 0, "lang": lang, "source": "synthetic"})
random.shuffle(rows)
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rows), encoding="utf-8")
